/**
 * Deterministic template selection via hash(eventId).
 */
export function pickTemplate(type: ActivityEventType, eventId: string): string {
  const templates = TEMPLATES[type];
  const hash = simpleHash(eventId);
  return templates[hash % templates.length]!;
}

/**
 * Replace {variable} placeholders with data values.
 */
export function interpolate(template: string, data: Record<string, unknown>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = data[key];
    if (value === undefined || value === null) return match;
    if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') {
      return String(value);
    }
    return match;
  });
}

/**
 * Simple non-cryptographic hash for deterministic selection.
 */
function simpleHash(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = ((hash << 5) - hash + char) | 0;
  }
  return Math.abs(hash);
}
